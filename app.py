@app.route("/generate", methods=["POST"])
def generate():
    data = {
        "patient_name": request.form.get("patient_name", ""),
        "patient_id": request.form.get("patient_id", ""),
        "date_of_assessment": request.form.get("date_of_assessment", ""),
        "assessor_name": request.form.get("assessor_name", ""),
        "diagnosis": request.form.get("diagnosis", ""),
        "health_condition": request.form.get("health_condition", ""),
        "personal_factors": request.form.get("personal_factors", ""),
        "body_functions": {},
        "body_structures": {},
        "activities_participation": {},
        "environmental_factors": {},
        "additional_notes": request.form.get("additional_notes", ""),
        "goals": request.form.get("goals", ""),
        "generated_date": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
    }

    qualifier_map = {q["value"]: q["label"] for q in QUALIFIERS}
    env_qualifier_map = {q["value"]: q["label"] for q in ENV_QUALIFIERS}

    for category in ICF_CATEGORIES.keys():
        is_env = category == "environmental_factors"
        is_ap = category == "activities_participation"
        for item in ICF_CATEGORIES[category]:
            note = request.form.get(f"{item['code']}_note", "").strip()
            if is_ap:
                perf = request.form.get(f"{item['code']}_performance", "")
                cap = request.form.get(f"{item['code']}_capacity", "")
                if perf or cap or note:
                    data[category][item["code"]] = {
                        "name": item["name"],
                        "performance_qualifier": perf,
                        "performance_label": qualifier_map.get(perf, ""),
                        "capacity_qualifier": cap,
                        "capacity_label": qualifier_map.get(cap, ""),
                        "note": note,
                    }
            else:
                qm = env_qualifier_map if is_env else qualifier_map
                qualifier = request.form.get(f"{item['code']}", "")
                if qualifier or note:
                    data[category][item["code"]] = {
                        "name": item["name"],
                        "qualifier": qualifier,
                        "qualifier_label": qm.get(qualifier, ""),
                        "note": note,
                    }

    return render_template("result.html", data=data)


@app.route("/api/generate", methods=["POST"])
def api_generate():
    json_data = request.get_json()
    result = {
        "patient_name": json_data.get("patient_name", ""),
        "patient_id": json_data.get("patient_id", ""),
        "date_of_assessment": json_data.get("date_of_assessment", ""),
        "assessor_name": json_data.get("assessor_name", ""),
        "diagnosis": json_data.get("diagnosis", ""),
        "health_condition": json_data.get("health_condition", ""),
        "assessments": {},
        "additional_notes": json_data.get("additional_notes", ""),
        "goals": json_data.get("goals", ""),
        "generated_date": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
    }
    for category_key, items in ICF_CATEGORIES.items():
        result["assessments"][category_key] = {}
        for item in items:
            qualifier = json_data.get(item["code"], "")
            note = json_data.get(f"{item['code']}_note", "").strip()
            if qualifier or note:
                entry = {
                    "name": item["name"],
                    "qualifier": qualifier,
                }
                if note:
                    entry["note"] = note
                result["assessments"][category_key][item["code"]] = entry
    return jsonify(result)


