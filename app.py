@app.route("/msk/flashcards/data")
def msk_flashcards_data():
    mode = request.args.get("mode", "tests")
    joint = request.args.get("joint", "all")
    cards = []

    if mode == "tests" or mode == "all":
        for j_key, j_data in MSK_SPECIAL_TESTS.items():
            if joint != "all" and joint != j_key:
                continue
            for t in j_data["tests"]:
                cards.append({
                    "id": f"test-{j_key}-{t['name']}",
                    "joint": j_data["label"],
                    "joint_key": j_key,
                    "mode": "tests",
                    "front": t["name"],
                    "back_title": t["name"],
                    "back_details": [
                        ("Purpose", t["purpose"]),
                        ("Procedure", t["procedure"]),
                        ("Positive Sign", t["positive_sign"]),
                    ],
                    "extra_tags": [
                        f'Sens: {"%.0f" % (t["sensitivity"] * 100) if t.get("sensitivity") else "—"}%',
                        f'Spec: {"%.0f" % (t["specificity"] * 100) if t.get("specificity") else "—"}%',
                    ] if t.get("sensitivity") or t.get("specificity") else [],
                    "image": t.get("image", None),
                    "notes": t.get("notes", ""),
                })

    if mode == "resistance" or mode == "all":
        for j_key, j_data in MSK_MUSCLE_TESTS.items():
            if joint != "all" and joint != j_key:
                continue
            for m in j_data["movements"]:
                cards.append({
                    "id": f"resist-{j_key}-{m['movement']}",
                    "joint": j_data["label"],
                    "joint_key": j_key,
                    "mode": "resistance",
                    "front": m["movement"],
                    "back_title": m["movement"],
                    "back_details": [
                        ("Primary Muscle", m["primary_muscle"]),
                        ("Other Muscles", ", ".join(m["other_muscles"])),
                        ("Nerve Root", m["nerve_root"]),
                        ("Peripheral Nerve", m["peripheral_nerve"]),
                        ("Patient Position", m["patient_position"]),
                        ("Procedure", m["procedure"]),
                        ("Substitutions", m["substitutions"]),
                    ],
                    "extra_tags": [m["primary_muscle"], m["nerve_root"]],
                    "image": m.get("image", None),
                    "image2": m.get("image2", None),
                    "notes": "",
                })

    if request.args.get("shuffle") == "1":
        import random
        random.shuffle(cards)

    return jsonify(cards)


